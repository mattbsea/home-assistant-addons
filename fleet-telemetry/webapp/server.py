def _save_config(patch):
    """Deep-merge patch into the on-disk settings file (atomic write, chmod 600). Returns the merged config."""
    # Merge over what is actually on disk (not the defaults) so we never write defaults the user
    # has not chosen, then re-read through _load_config for the caller.
    current = {}
    try:
        with open(WIZARD_CONFIG_FILE) as fh:
            current = json.load(fh) or {}
    except (OSError, ValueError):
        current = {}
    if not isinstance(current, dict):
        current = {}
    _deep_merge(current, patch)
    dirpath = os.path.dirname(WIZARD_CONFIG_FILE) or "."
    os.makedirs(dirpath, exist_ok=True)
    fd, tmp = tempfile.mkstemp(dir=dirpath, suffix=".tmp")
