def _npm_token(base, email, password):
    base = base.rstrip("/")
    status, body = _http_json("POST", base + "/api/tokens",
                              data={"identity": email, "secret": password})
    if isinstance(body, dict) and body.get("token"):
        return body["token"], None
    return None, f"NPM auth failed (HTTP {status}): {str(body)[:200]}"


def _npm_find_proxy_host(base, token, domain):
    """Return an existing proxy-host id serving `domain`, or None."""
    status, body = _http_json("GET", base.rstrip("/") + "/api/nginx/proxy-hosts",
                              headers={"Authorization": "Bearer " + token})
    if isinstance(body, list):
        d = domain.lower()
        for h in body:
            names = [n.lower() for n in (h.get("domain_names") or [])]
            if d in names:
                return h.get("id")
    return None


def _addon_host_port(internal_port):
    """Host-side port mapped to <internal_port>/tcp, read live from the add-on's Network settings via
    the Supervisor. NPM forwards to the HOST port, which the user can remap in the Network tab — so
    we never assume 1:1. Falls back to the internal port if the mapping is unknown/unexposed."""
    token = os.environ.get("SUPERVISOR_TOKEN", "")
    if not token:
        return internal_port
    try:
        _status, body = _http_json("GET", "http://supervisor/addons/self/info",
                                   headers={"Authorization": "Bearer " + token}, timeout=10)
        net = (body.get("data") or {}).get("network") if isinstance(body, dict) else None
        mapped = net.get(f"{internal_port}/tcp") if isinstance(net, dict) else None
        if isinstance(mapped, int) and mapped > 0:
            return mapped
    except Exception:
        pass
    return internal_port


def _create_pubkey_proxy_host(cfg):
    """Create (or reuse) an NPM proxy host that serves the public key over HTTPS for pubkey_domain.

    Forwards HTTP to the add-on's host-exposed pubkey listener and requests a Let's Encrypt cert.
    Returns {"ok": bool, "id"?, "error"?}.
    """
    npm = cfg.get("npm", {})
    base = (npm.get("url") or "").rstrip("/")
    domain = (cfg.get("tesla", {}).get("pubkey_domain") or "").strip().lower()
    forward_host = (npm.get("forward_host") or "").strip()
    email = npm.get("email") or ""
    if not base or not email or not npm.get("password"):
        return {"ok": False, "error": "NPM url, email and password must be set first (step 4)."}
    if not domain:
        return {"ok": False, "error": "Set your public-key domain first."}
    if not forward_host:
        return {"ok": False, "error": "Set the HA host IP (forward_host) NPM should forward to (step 4)."}

    token, err = _npm_token(base, email, npm["password"])
    if not token:
        return {"ok": False, "error": err}
    auth = {"Authorization": "Bearer " + token}

    # Reuse an existing host for this domain rather than creating a duplicate.
    existing = _npm_find_proxy_host(base, token, domain)
    if existing:
        return {"ok": True, "id": existing, "reused": True}

    # Request a Let's Encrypt certificate for the domain. DNS for the domain must already point at
    # NPM (HTTP-01 challenge) — surface failures rather than masking them.
    cert_payload = {
        "domain_names": [domain],
        "meta": {"letsencrypt_email": email, "letsencrypt_agree": True, "dns_challenge": False},
        "provider": "letsencrypt",
    }
    cstatus, cbody = _http_json("POST", base + "/api/nginx/certificates", headers=auth, data=cert_payload, timeout=120)
    cert_id = cbody.get("id") if isinstance(cbody, dict) else None
    if not cert_id:
        return {"ok": False, "error": f"Let's Encrypt cert request failed (HTTP {cstatus}): {str(cbody)[:300]}. "
                                      f"Confirm {domain} resolves to your public IP and ports 80/443 reach NPM."}

    host_payload = {
        "domain_names": [domain],
        "forward_scheme": "http",
        "forward_host": forward_host,
        "forward_port": _addon_host_port(PUBKEY_PORT),
        "certificate_id": cert_id,
        "ssl_forced": True,
        "block_exploits": True,
        "caching_enabled": False,
        "allow_websocket_upgrade": False,
        "access_list_id": 0,
        "advanced_config": "",
        "locations": [],
        "http2_support": False,
        "hsts_enabled": False,
        "hsts_subdomains": False,
        "meta": {"letsencrypt_agree": False, "dns_challenge": False},
    }
    hstatus, hbody = _http_json("POST", base + "/api/nginx/proxy-hosts", headers=auth, data=host_payload, timeout=60)
    host_id = hbody.get("id") if isinstance(hbody, dict) else None
    if not host_id:
        return {"ok": False, "error": f"Proxy host creation failed (HTTP {hstatus}): {str(hbody)[:300]}"}
    return {"ok": True, "id": host_id, "certificate_id": cert_id}


def _npm_find_stream(base, token, incoming_port):
    """Return an existing TCP-passthrough stream id on `incoming_port`, or None."""
    status, body = _http_json("GET", base.rstrip("/") + "/api/nginx/streams",
                              headers={"Authorization": "Bearer " + token})
    if isinstance(body, list):
        for s in body:
            if int(s.get("incoming_port", -1)) == int(incoming_port):
                return s.get("id")
    return None


def _create_telemetry_stream(cfg):
    """Create (or reuse) an NPM Stream: a Layer-4 TCP passthrough from the public telemetry port to
    the add-on's mTLS port. NO SSL termination (certificate_id 0) — the add-on terminates mTLS
    itself. Returns {"ok": bool, "id"?, "error"?}.
    """
    npm = cfg.get("npm", {})
    tesla = cfg.get("tesla", {})
    base = (npm.get("url") or "").rstrip("/")
    email = npm.get("email") or ""
    forward_host = (npm.get("forward_host") or "").strip()
    try:
        port = int(tesla.get("telemetry_port") or 4443)
    except (TypeError, ValueError):
        port = 4443
    if not base or not email or not npm.get("password"):
        return {"ok": False, "error": "NPM url, email and password must be set first (step 3)."}
    if not forward_host:
        return {"ok": False, "error": "Set the HA host IP (forward_host) NPM should forward to (step 3)."}

    token, err = _npm_token(base, email, npm["password"])
    if not token:
        return {"ok": False, "error": err}
    auth = {"Authorization": "Bearer " + token}

    existing = _npm_find_stream(base, token, port)
    if existing:
        return {"ok": True, "id": existing, "reused": True, "incoming_port": port}

    fwd_port = _addon_host_port(TELEMETRY_PORT)   # host port mapped to the add-on (from Network settings)
    payload = {
        "incoming_port": port,
        "forwarding_host": forward_host,
        "forwarding_port": fwd_port,
        "tcp_forwarding": True,
        "udp_forwarding": False,
        "certificate_id": 0,                 # passthrough — do NOT terminate TLS (mTLS-only server)
        "meta": {},
    }
    sstatus, sbody = _http_json("POST", base + "/api/nginx/streams", headers=auth, data=payload, timeout=60)
    stream_id = sbody.get("id") if isinstance(sbody, dict) else None
    if not stream_id:
        return {"ok": False, "error": f"Stream creation failed (HTTP {sstatus}): {str(sbody)[:300]}. "
                                      f"Confirm port {port} is forwarded from your router to NPM."}
    return {"ok": True, "id": stream_id, "incoming_port": port,
            "forwarding_host": forward_host, "forwarding_port": fwd_port}


