def _deep_merge(base, patch):
    """Recursively merge patch into base (dicts merged, everything else replaced)."""
    for k, v in patch.items():
        if isinstance(v, dict) and isinstance(base.get(k), dict):
            _deep_merge(base[k], v)
        else:
            base[k] = v
    return base


