# ---------------------------------------------------------------------------
# Dedicated, internet-facing public-key listener (reached via the NPM proxy host).
# It is a SEPARATE trust zone from the ingress dashboard: it serves ONLY the Tesla 3p
# public key and 404s everything else — no dashboard, no wizard, no /api.
# ---------------------------------------------------------------------------
class PubkeyHandler(BaseHTTPRequestHandler):
    def log_message(self, *a):
        pass

    def do_GET(self):
        path = self.path.split("?", 1)[0]
        if path == PUBKEY_WELL_KNOWN_PATH:
            pem = _public_key_pem()
            if pem:
                self.send_response(200)
                self.send_header("Content-Type", "application/x-pem-file")
                self.send_header("Content-Length", str(len(pem)))
                self.send_header("Cache-Control", "no-store")
                self.end_headers()
                if self.command != "HEAD":
                    self.wfile.write(pem)
                return
            self.send_error(404, "public key not generated yet")
            return
        self.send_error(404, "not found")

    do_HEAD = do_GET


def _serve_pubkey():
    try:
        srv = ThreadingHTTPServer(("0.0.0.0", PUBKEY_PORT), PubkeyHandler)
    except OSError as e:
        print(f"[fleet-telemetry-web] pubkey listener failed to bind :{PUBKEY_PORT}: {e}", flush=True)
        return
    print(f"[fleet-telemetry-web] public-key listener on :{PUBKEY_PORT} (serves only {PUBKEY_WELL_KNOWN_PATH})", flush=True)
    srv.serve_forever()


def main():
    threading.Thread(target=_tail_records, daemon=True).start()
    threading.Thread(target=_serve_pubkey, daemon=True).start()
    srv = ThreadingHTTPServer(("0.0.0.0", PORT), Handler)
    print(f"[fleet-telemetry-web] dashboard listening on :{PORT}", flush=True)
