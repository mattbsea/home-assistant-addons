def _generate_keypair(force=False):
    cfg = _load_config()
    if cfg.get("tesla", {}).get("partner_registered") and not force:
        if os.path.exists(PRIVATE_KEY_FILE) and os.path.exists(PUBLIC_KEY_FILE):
            return {"ok": True, "already": True, "fingerprint": _key_fingerprint()}
        return {"ok": False, "error": "Partner already registered but key files are missing — "
                                      "regenerating would invalidate the registration. Re-register after forcing."}
    if os.path.exists(PRIVATE_KEY_FILE) and not force:
        return {"ok": True, "already": True, "fingerprint": _key_fingerprint()}
    os.makedirs(os.path.dirname(PRIVATE_KEY_FILE), exist_ok=True)
    try:
        subprocess.run(["openssl", "ecparam", "-name", "prime256v1", "-genkey", "-noout",
                        "-out", PRIVATE_KEY_FILE], check=True, capture_output=True, timeout=15)
        os.chmod(PRIVATE_KEY_FILE, 0o600)
        subprocess.run(["openssl", "ec", "-in", PRIVATE_KEY_FILE, "-pubout",
                        "-out", PUBLIC_KEY_FILE], check=True, capture_output=True, timeout=15)
    except subprocess.CalledProcessError as e:
        return {"ok": False, "error": f"openssl failed: {(e.stderr or b'').decode('utf-8', 'replace')[:200]}"}
    except Exception as e:
        return {"ok": False, "error": f"keypair generation failed: {e}"}
    _save_config({"tesla": {"keypair_generated": True}})
    return {"ok": True, "fingerprint": _key_fingerprint()}


def _key_fingerprint():
    try:
        out = subprocess.run(["openssl", "ec", "-in", PRIVATE_KEY_FILE, "-pubout", "-outform", "DER"],
                             capture_output=True, timeout=10)
        if out.returncode == 0:
            import hashlib
            return hashlib.sha256(out.stdout).hexdigest()[:32]
    except Exception:
        pass
    return ""


def _public_key_pem():
    try:
        with open(PUBLIC_KEY_FILE, "rb") as fh:
            return fh.read()
    except OSError:
        return None


