# Small HTTP helpers (urllib) shared by the NPM client and the Tesla OAuth flows
# ---------------------------------------------------------------------------
def _http_json(method, url, headers=None, data=None, timeout=30):
    """Issue an HTTP request and return (status, parsed_json_or_text). Never raises on HTTP error."""
    body = None
    hdrs = dict(headers or {})
    if data is not None:
        if isinstance(data, (dict, list)):
            body = json.dumps(data).encode()
            hdrs.setdefault("Content-Type", "application/json")
        elif isinstance(data, str):
            body = data.encode()
        else:
            body = data
    req = urllib.request.Request(url, data=body, headers=hdrs, method=method)
    try:
        with urllib.request.urlopen(req, timeout=timeout) as r:
            raw = r.read()
            try:
                return r.status, json.loads(raw.decode("utf-8"))
            except (ValueError, UnicodeDecodeError):
                return r.status, raw.decode("utf-8", errors="replace")
    except urllib.error.HTTPError as e:
        try:
            raw = e.read().decode("utf-8", errors="replace")
        except Exception:
            raw = ""
        try:
            return e.code, json.loads(raw)
        except ValueError:
            return e.code, raw
    except Exception as e:
        return 0, str(e)


def _form_post(url, fields, timeout=30):
    """POST application/x-www-form-urlencoded; return (status, parsed)."""
    body = urllib.parse.urlencode(fields).encode()
    return _http_json("POST", url, headers={"Content-Type": "application/x-www-form-urlencoded"},
                      data=body, timeout=timeout)


